#!/usr/bin/env bash
# Regenerates src/codes.rs from data/codes.txt.
set -euo pipefail
{
    echo '// @generated by gen.sh from data/codes.txt. Do not edit.'
    echo 'pub fn reason(code: u16) -> Option<&'"'"'static str> {'
    echo '    match code {'
    sort -n data/codes.txt | while read -r code text; do
        echo "        $code => Some(\"$text\"),"
    done
    echo '        _ => None,'
    echo '    }'
    echo '}'
} >src/codes.rs
